"""
Mock / Simulator Model Client.
Provides deterministic responses, block replacements, and controllable failure
modes (429 rate limit, timeouts, errors) for testing failover and handoff logic.
"""

import time
from typing import Optional, Dict, Any

from .base import (
    BaseModelClient,
    RateLimitException,
    TimeoutException,
    ModelExecutionException
)
from ..types import ModelConfig, ModelResponse


class MockModelClient(BaseModelClient):
    """
    Mock model client supporting controllable responses and failure injection.
    Ideal for unit testing, offline demonstrations, and failover validation.
    """

    def __init__(self, config: ModelConfig, custom_reply: Optional[str] = None):
        super().__init__(config)
        self.custom_reply = custom_reply
        self.call_count = 0

    def generate(self, system_prompt: str, user_prompt: str) -> ModelResponse:
        self.call_count += 1
        start_time = time.time()

        # Check for simulated failures
        if self.config.simulate_429:
            raise RateLimitException(
                message=f"Simulated HTTP 429: Rate limit exceeded on model '{self.name}'.",
                model_name=self.name
            )

        if self.config.simulate_timeout:
            raise TimeoutException(
                message=f"Simulated HTTP 408: Request to '{self.name}' timed out after {self.config.timeout_seconds}s.",
                model_name=self.name
            )

        if self.config.simulate_error:
            raise ModelExecutionException(
                message=f"Simulated HTTP 500: Internal server error on model '{self.name}'.",
                status_code=500,
                model_name=self.name
            )

        # If custom reply is provided, return it
        if self.custom_reply:
            latency = time.time() - start_time
            return ModelResponse(
                raw_text=self.custom_reply,
                model_name=self.name,
                provider=self.provider,
                latency_seconds=round(latency, 4),
                token_usage={"prompt_tokens": len(user_prompt) // 4, "completion_tokens": len(self.custom_reply) // 4}
            )

        # Dynamic mock response based on prompt contents
        response_text = self._generate_intelligent_mock_reply(user_prompt)
        latency = time.time() - start_time

        return ModelResponse(
            raw_text=response_text,
            model_name=self.name,
            provider=self.provider,
            latency_seconds=round(latency, 4),
            token_usage={"prompt_tokens": len(user_prompt) // 4, "completion_tokens": len(response_text) // 4}
        )

    def _generate_intelligent_mock_reply(self, prompt: str) -> str:
        # If wrapped in System Kernel prompt format, isolate task prompt
        task_section = prompt
        if "### [CURRENT TASK PROMPT]" in prompt:
            task_section = prompt.split("### [CURRENT TASK PROMPT]")[1].strip()

        lower_task = task_section.lower()

        # If user asks to create a file
        if "create" in lower_task and "file" in lower_task:
            # Check for requested file name in task section
            filename = "src/example.py"
            for word in task_section.split():
                if "." in word and not word.endswith("."):
                    clean = word.strip("`'\"(),:;")
                    if any(clean.endswith(ext) for ext in (".py", ".js", ".ts", ".json", ".md", ".txt", ".html")):
                        filename = clean
                        break

            return f"""I have created `{filename}` with the requested implementation.

<<<FILE_UPDATE:{filename}>>>
\"\"\"
Generated by System Kernel ({self.name}).
\"\"\"

def greet(name: str = "World") -> str:
    return f"Hello, {{name}}! Generated by {self.name}."

if __name__ == "__main__":
    print(greet())
<<<END_FILE_UPDATE>>>
"""

        # If user asks to fix or replace a block or function
        if "fix" in lower_task or "replace" in lower_task or "bug" in lower_task or "implement" in lower_task:
            # Check if active file is in prompt
            active_file = "src/main.py"
            if "ACTIVE FILE: " in prompt:
                try:
                    active_file = prompt.split("ACTIVE FILE: ")[1].split("\n")[0].strip()
                except Exception:
                    pass

            return f"""I analyzed the workspace snapshot and identified the fix needed in `{active_file}`.
Applying targeted block replacement to resolve the issue:

<<<SEARCH_REPLACE:{active_file}>>>
<<<<<<< SEARCH
# TODO: Implement calculation
pass
=======
# Fixed and implemented by {self.name}
result = [x * 2 for x in items]
return result
>>>>>>>
<<<END_SEARCH_REPLACE>>>

The block has been replaced cleanly with zero context drift."""

        # Default explanation and code
        return f"""I have processed your request: '{prompt[:60]}...' using model `{self.name}`.
The workspace state snapshot was parsed successfully and all open buffers remain synchronized.
"""
