"""
In-Memory Pre-Commit Syntax & Sanity Validator.
Validates code syntax before mutations are committed to buffers or disk,
preventing broken code generated by LLMs from corrupting workspace state.
"""

import ast
import json
from pathlib import Path
from typing import Tuple, Optional


class SyntaxValidator:
    """
    Validates code syntax across languages prior to state mutation.
    """

    @classmethod
    def validate(cls, file_path: str, code: str) -> Tuple[bool, Optional[str]]:
        """
        Validates the code syntax based on file extension.
        Returns:
            (is_valid: bool, error_message: Optional[str])
        """
        if not code.strip():
            return True, None

        ext = Path(file_path).suffix.lower()

        try:
            # Python AST parsing
            if ext == ".py":
                ast.parse(code, filename=file_path)
                return True, None

            # JSON validation
            elif ext == ".json":
                json.loads(code)
                return True, None

            # Basic bracket / parenthesis balance for JS / TS / CSS / HTML
            elif ext in (".js", ".ts", ".jsx", ".tsx", ".css", ".html"):
                return cls._check_bracket_balance(code)

            return True, None

        except SyntaxError as e:
            return False, f"Python SyntaxError at line {e.lineno}: {e.msg}"
        except json.JSONDecodeError as e:
            return False, f"JSON SyntaxError at line {e.lineno}, col {e.colno}: {e.msg}"
        except Exception as e:
            return False, f"Syntax validation error: {str(e)}"

    @staticmethod
    def _check_bracket_balance(code: str) -> Tuple[bool, Optional[str]]:
        """Checks for unclosed braces, brackets, and parentheses ignoring strings."""
        stack = []
        pairs = {')': '(', '}': '{', ']': '['}
        in_single_str = False
        in_double_str = False
        escaped = False

        for idx, char in enumerate(code):
            if escaped:
                escaped = False
                continue
            if char == '\\':
                escaped = True
                continue

            if char == "'" and not in_double_str:
                in_single_str = not in_single_str
                continue
            if char == '"' and not in_single_str:
                in_double_str = not in_double_str
                continue

            if in_single_str or in_double_str:
                continue

            if char in "({[":
                stack.append((char, idx))
            elif char in ")}]":
                if not stack:
                    return False, f"Unmatched closing '{char}' near character {idx}"
                top, _ = stack.pop()
                if pairs[char] != top:
                    return False, f"Mismatched bracket: expected match for '{top}', got '{char}'"

        if stack:
            unclosed, pos = stack[-1]
            return False, f"Unclosed '{unclosed}' near character {pos}"

        return True, None
